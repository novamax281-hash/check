package com.example.placement.service;

import io.micrometer.common.util.StringUtils;
import jakarta.mail.internet.MimeMessage;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.mail.javamail.JavaMailSender;
import org.springframework.mail.javamail.MimeMessageHelper;
import org.springframework.stereotype.Service;

@Service
public class EmailCsvService {

    private static final Logger log = LoggerFactory.getLogger(EmailCsvService.class);

    private final JavaMailSender mailSender;

    public EmailCsvService(JavaMailSender mailSender) {
        this.mailSender = mailSender;
    }

    public void sendCsv(String recipient, String csvContent, String filename) {
        if (StringUtils.isBlank(recipient)) {
            throw new IllegalArgumentException("Recipient email is required");
        }
        if (csvContent == null || csvContent.isEmpty()) {
            throw new IllegalArgumentException("CSV content is empty");
        }
        try {
            MimeMessage message = mailSender.createMimeMessage();
            MimeMessageHelper helper = new MimeMessageHelper(message, true, "UTF-8");
            helper.setTo(recipient.trim());
            helper.setSubject("Student Data Export - " + filename);
            helper.setText("Please find the attached student data (" + filename + ").\n\n"
                    + "Generated by PlacementLink on behalf of the placement coordinator.", "text/plain");

            helper.addAttachment(filename, new jakarta.activation.DataSource() {
                @Override
                public java.io.InputStream getInputStream() throws java.io.IOException {
                    return new java.io.ByteArrayInputStream(
                            csvContent.getBytes(java.nio.charset.StandardCharsets.UTF_8));
                }

                @Override
                public java.io.OutputStream getOutputStream() {
                    throw new UnsupportedOperationException();
                }

                @Override
                public String getContentType() {
                    return "text/csv";
                }

                @Override
                public String getName() {
                    return filename;
                }
            });

            mailSender.send(message);
        } catch (jakarta.mail.MessagingException exception) {
            log.error("Could not send CSV email to {}", recipient, exception);
            throw new RuntimeException("Could not send the CSV email. Please try again.");
        }
    }
}